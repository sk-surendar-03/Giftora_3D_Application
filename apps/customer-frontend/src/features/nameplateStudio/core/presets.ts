function buildTemplate(
  id: string,
  title: string,
  subtitle: string,
  theme: ThemeCategory,
  type: NameplateTypeId,
  overrides: Partial<Omit<NameplateDesign, 'id'>>,
): NameplateTemplate {
  const base = createDefaultDesign();
  const merged: Omit<NameplateDesign, 'id'> = {
    ...base,
    ...overrides,
    name: title,
    theme,
    type,
  };
  return {
    id,
    title,
    subtitle,
    theme,
    type,
    accentHex: merged.lines[0]?.color ?? '#d4af37',
    previewBgHex: merged.baseColor,
    design: merged,
  };
}

