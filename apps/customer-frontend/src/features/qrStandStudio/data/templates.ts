export function createDesignFromTemplate(templateId: TemplateId): StandDesign {
  const tpl = TEMPLATES.find((t) => t.id === templateId) || TEMPLATES[0];
  const colorPreset = COLOR_PRESETS[0];

  return {
    id: `qr-stand-${Date.now()}`,
    name: tpl.name,
    templateId: tpl.id,
    dimensions: { ...tpl.defaultDimensions },
    printingMode: 'raised',
    qrCodes: [
      {
        id: 'primary-qr',
        label: 'Front QR',
        type: 'url',
        fields: createDefaultQRFields(),
        sizeMm: tpl.defaultQrSizeMm,
        errorCorrection: 'H',
        quietZone: 4,
        fgColor: colorPreset.qrColor,
        bgColor: colorPreset.standColor,
        positionX: 0,
        positionY: tpl.defaultQrPosY,
        face: 'front',
        visible: true,
      },
    ],
    texts: [
      {
        id: 'headline-text',
        content: 'SCAN TO CONNECT',
        presetRole: 'business_name',
        category: 'Bold',
        fontSizeMm: 7,
        letterSpacing: 0.8,
        align: 'center',
        xMm: 0,
        yMm: tpl.defaultTextPosY,
        rotationDeg: 0,
        color: colorPreset.textColor,
        mode: 'raised',
        depthMm: 1.0,
        face: 'front',
        visible: true,
      },
    ],
    logo: {
      enabled: false,
      dataUrl: null,
      fileName: null,
      isSvg: false,
      svgText: null,
      placement: 'center',
      sizeMm: 16,
      xMm: 0,
      yMm: 0,
      frameStyle: 'circle',
      frameColor: colorPreset.accentColor,
      backingColor: colorPreset.standColor,
      mode: 'raised',
      depthMm: 0.8,
    },
    decorations: [],
    colors: {
      presetId: colorPreset.id,
      standColor: colorPreset.standColor,
      baseColor: colorPreset.baseColor,
      frameColor: colorPreset.frameColor,
      qrColor: colorPreset.qrColor,
      textColor: colorPreset.textColor,
      accentColor: colorPreset.accentColor,
      materialType: colorPreset.materialType,
      rainbowPreview: false,
    },
    visibility: {
      base: tpl.hasBase,
      body: true,
      frame: true,
      qr: true,
      text: true,
      logo: false,
      decorations: true,
    },
    updatedAt: Date.now(),
  };
}
