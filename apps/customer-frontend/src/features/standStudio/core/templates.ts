export function instantiateTemplate(preset: TemplatePreset, currentPrint?: DesignConfig['print']): DesignConfig {
  const base = createDefaultDesign(preset.category, preset.themeId);
  const theme = DESIGN_THEMES[preset.themeId];
  return {
    ...base,
    id: `tpl-${preset.id}-${Date.now()}`,
    name: preset.name,
    category: preset.category,
    phone: { ...base.phone, ...(preset.config.phone || {}) },
    pen: { ...base.pen, ...(preset.config.pen || {}) },
    combined: { ...base.combined, ...(preset.config.combined || {}) },
    personalization: { ...base.personalization, ...(preset.config.personalization || {}) },
    appearance: {
      themeId: preset.themeId,
      finish: preset.config.appearance?.finish ?? theme.finish,
      colors: { ...theme.colors, ...(preset.config.appearance?.colors || {}) },
    },
    print: currentPrint ? { ...currentPrint } : base.print,
    updatedAt: new Date().toISOString(),
  };
}
